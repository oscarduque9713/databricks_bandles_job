

---- CREAR TABLA SILVER -- CLIENTES

CREATE OR REFRESH STREAMING TABLE IDENTIFIER('${CATALOG}.ly_silver.CLIENTS') (
    ---- QUALITY CONSTRAINTS
    CONSTRAINT VALID_CLIENT_ID EXPECT ( CLIENT_ID IS NOT NULL) ON VIOLATION FAIL UPDATE,
    CONSTRAINT NOT_NULL_EMAIL EXPECT ( EMAIL IS NOT NULL) 
) AS 
SELECT 
    * EXCEPT (SOURCE_FILE)
FROM STREAM (${CATALOG}.ly_bronze.CLIENTS_RW) ;


----- DEFINIR TABLA ORDERS

CREATE OR REFRESH STREAMING TABLE IDENTIFIER('${CATALOG}.ly_silver.ORDERS') (
    --- SCHEMA 
    ORDER_ID STRING,
    ORDER_TIMESTAMP TIMESTAMP,
    CLIENT_ID STRING,
    CATEGORY STRING,
    TOTAL_QTY INTEGER,
    TOTAL_PRICE DECIMAL(10, 2),
    SOURCE_FILE STRING,
    IS_QUARANTINED BOOLEAN,
    QUARANTINE_REASON STRING
    
    ---- QUALITY CONSTRAINTS
    CONSTRAINT VALID_ORDER_ID EXPECT ( ORDER_ID IS NOT NULL) ON VIOLATION FAIL UPDATE,
    CONSTRAINT VALID_CLIENT EXPECT (CLIENT_ID RLIKE '^CLI[0-9]+$'),
    CONSTRAINT TOTAL_QTY_POS EXPECT ((TOTAL_QTY >= 0) OR (TOTAL_PRICE >= 0))
);


CREATE FLOW APPEND_ORDERS_QITH_QA_LOGIC 
