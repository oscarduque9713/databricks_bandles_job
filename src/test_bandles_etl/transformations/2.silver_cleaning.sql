------ ORDERS CLEANED 

CREATE OR REFRESH STREAMING TABLE IDENTIFIER('${CATALOG}.ly_silver.ORDERS_CLEANED')
COMMENT 'Registros que pasan las validaciones de calidad'
AS 
SELECT * EXCEPT ( IS_QUARANTINED, QUARANTINE_REASON, SOURCE_FILE)
FROM STREAM (${CATALOG}.ly_silver.ORDERS)
WHERE IS_QUARANTINED = false;


------ QUARANTINE TABLE 

CREATE OR REFRESH STREAMING TABLE IDENTIFIER('${CATALOG}.ly_silver.ORDERS_QUARANTINED')
COMMENT 'Registros que fallan alguna de las validaciones de calidad'
TBLPROPERTIES(
    'pipeline.reset,allowed' = FALSE
)
AS 
SELECT *,
    CURRENT_DATE AS INS_DATE
FROM STREAM (${CATALOG}.ly_silver.ORDERS)
WHERE IS_QUARANTINED = TRUE;



